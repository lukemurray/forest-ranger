/** A random forest word that isn't one of the recently-shown ones (pass the last
 *  few), so it rotates without near-term repeats. */
export function nextForestWord(recent: readonly string[] = []): string {
	let w = FOREST_WORDS[Math.floor(Math.random() * FOREST_WORDS.length)];
	for (let guard = 0; recent.includes(w) && guard < 50; guard++) {
		w = FOREST_WORDS[Math.floor(Math.random() * FOREST_WORDS.length)];
	}
	return w;
}
